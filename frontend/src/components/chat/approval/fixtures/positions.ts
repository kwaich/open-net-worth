type Consumption = { realized_gain: number | null }

// The sale's gain is the sum of its lots' gains unless a case overrides it (fees, a transfer,
// an unknown basis).
const gainOf = (consumptions: Consumption[]) =>
  Math.round(consumptions.reduce((sum, c) => sum + (c.realized_gain ?? 0), 0) * 100) / 100

