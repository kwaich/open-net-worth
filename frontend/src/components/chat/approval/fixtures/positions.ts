const lot = (
  id: string,
  qty: number,
  cost: number | null,
  at: string,
  term: string,
  price = 615,
) => ({
  lot_id: id,
  qty,
  unit_cost: cost,
  cost_currency: 'USD',
  acquired_at: at,
  term,
  realized_gain: cost == null ? null : Math.round(qty * (price - cost) * 100) / 100,
})

