/** Lookup a country by its ISO-3166 alpha-2 code (case-insensitive). */
export function lookupByCode(code: string): Country | undefined {
  const upper = code.trim().toUpperCase()
  return COUNTRIES.find((c) => c.code === upper)
}

/** Lookup a country by its canonical English name (case-insensitive exact match). */
export function lookupByName(name: string): Country | undefined {
  const lower = name.trim().toLowerCase()
  return COUNTRIES.find((c) => c.name.toLowerCase() === lower)
}

