def _suggestions_model() -> str:
    """The 'suggestions' task model as a compound '<provider>:<model>' ref, or '' for
    the instance default. Routed through the provider-agnostic ``llm_seam`` (which
    resolves the provider per-ref), so ANY transport works — not just Anthropic."""
    try:
        from backend.db.model_config_store import ModelConfigStore

        return ModelConfigStore().task_model_override("suggestions") or ""
    except Exception as exc:
        logger.warning(
            "chat_suggestions: task model resolution failed (%s); using instance default", exc
        )
        return ""


# In-memory TTL cache for starter suggestions (portfolio context changes slowly).
# Follow-ups are turn-specific and never cached.
_STARTER_CACHE: dict[str, object] = {"value": None, "at": 0.0}
_STARTER_TTL_SEC = 300


class SuggestionsRequest(BaseModel):
    session_id: Optional[str] = None


class _Suggestions(BaseModel):
    """The structured suggestion shape. NOT min-length constrained — an empty list is a
    valid (best-effort) outcome, so 0 suggestions validates and the flow returns []."""

    suggestions: list[str] = Field(default_factory=list)


