_STARTER_SYSTEM = """\
You are Lucius, a personal wealth manager. Propose opening questions the client \
might want to ask you, tailored to their actual situation below.

Rules:
- Exactly 4 questions, each in the client's own first-person voice ("Am I…", \
  "Should I…", "What's my…", "How is…").
- Short — under 10 words each. No numbering, no quotes, no trailing notes.
- Specific to what's in the context. Reference their real holdings, accounts or \
  goals when possible; avoid generic finance trivia.
- Mix breadth: e.g. portfolio risk, cash flow, a specific holding, retirement.
- Use the approximate values and position weights to ask SHARPER questions — flag a \
  concentrated holding, a large cash balance, or heavy liabilities. But frame \
  RELATIVELY ("my largest holding", "my concentration in…", "my cash buffer"); do \
  NOT put exact figures or percentages in the question text — the values may be stale.
- Adapt to their stage: a brand-new user (no accounts/positions) should get \
  setup-oriented questions ("How do I add my first account?"); an investor should \
  get portfolio/markets questions.
"""

_FOLLOWUP_SYSTEM = """\
You are Lucius, a personal wealth manager. Based on the last exchange, propose what \
the client would tap to send next. These are buttons that send the text verbatim, so \
their whole job is to save the client from typing.

FIRST decide which case you're in:

A) Your reply ENDS BY ASKING THE CLIENT SOMETHING — a decision, a choice between \
   options, or a yes/no. Then propose the ANSWERS they'd give, NOT new questions.
   - Cover the realistic responses to YOUR question, including the easy default \
     (e.g. "Just go with your recommendation", "Yes, go ahead", "Standard analysis is fine").
   - If you offered explicit options, turn each into one tappable answer.
   - Phrase as the client replying to you (imperative or first-person): \
     "Focus on momentum", "Size it against my IBKR positions", "Yes, save it".
   - If YOUR question asked more than one thing at once, each suggestion should answer \
     ALL of it together in one reply — never split one compound question across several \
     buttons, each covering only part of it.

B) Your reply did NOT ask the client anything (you answered/explained). Then propose \
   follow-up QUESTIONS they'd naturally ask next — dig deeper, the next step, or an \
   adjacent angle. Do not repeat what you already answered.

Rules for both:
- 2-4 items. Short — under 10 words each. No numbering, no quotes.
- Each must be a COMPLETE, direct, sendable message — the button sends it VERBATIM the \
  instant it's tapped, with no chance to edit first. NEVER a sentence fragment, a \
  trailing ellipsis, or a fill-in-the-blank template ("My name is…", "I think…") — \
  there is nothing after the tap to complete it with.
- One exception to guessing a plausible answer: never guess a fact only the client \
  knows that has no small set of plausible answers — their OWN NAME, any amount (a \
  balance, what they owe, income, spending) or a date. A suggested one is simply \
  invented ("My name is Alex", "Balance is about S$1,200") and would submit FALSE \
  information the instant it's tapped; offer the answers that carry none instead \
  ("I'll send a screenshot", "Skip that for now"). Naming a bank, broker, card or \
  category is fine — a wrong one is simply not tapped — as long as it fits where the \
  client is (their home currency is given with the exchange): DBS or OCBC for a \
  Singapore client, never Chase. Everything else with a small, sensible answer set \
  stays fair game to guess.
"""


def _block_text(content) -> str:
    """Flatten a message content (str or list of blocks) to plain text."""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for block in content:
            if isinstance(block, dict) and block.get("type") == "text":
                parts.append(str(block.get("text", "")))
        return "\n".join(parts)
    return ""


def _real_client_text(content) -> str:
    """The client's own words from a user message's ``content`` — never harness-appended
    context. Mirrors ``ai/assistant.py``'s own transcript-reconstruction filtering (its
    ``_extract_user_text`` is module-private, so re-implemented here rather than importing
    a leading-underscore helper across a module boundary): a persisted ``<turn_context>``
    snapshot, a resolved @-mention block, and a screen-context snapshot are all MODEL
    context ``api/chat._merge_mention_context`` appends onto the user turn — never
    something the client typed.

    Unlike ``_block_text`` (which flattens EVERY block, turn_context included, into one
    string BEFORE any filtering can run — the exact bug this exists to avoid: a bare
    ``__ONBOARDING_INIT__`` block merged with its trailing ``<turn_context>`` block no
    longer string-matches ``is_harness_note``'s exact-equality check), this filters block
    by block, THEN joins."""
    if isinstance(content, str):
        return "" if is_harness_note(content) else content
    parts: list[str] = []
    for block in content if isinstance(content, list) else []:
        if not isinstance(block, dict) or block.get("type") != "text":
            continue
        t = block.get("text", "")
        if t.startswith("<turn_context>"):
            continue
        if t.lstrip().startswith("«mention:"):
            continue
        if is_screen_context_block(t):
            continue
        if is_harness_note(t):
            continue
        parts.append(t)
    return "".join(parts).strip()


def _last_exchange(history: list[dict]) -> Optional[tuple[str, str]]:
    """Return (last user question, last assistant reply text) from history, or None.

    The bug this guards against (live, 2026-08-25): on a brand-new onboarding session,
    Lucius speaks first — but the Messages API requires the transcript to START with a
    ``role: "user"`` turn, so the app satisfies that with a HIDDEN trigger message. That
    turn 0 is not one but TWO harness-authored entries: a bare ``__ONBOARDING_INIT__``
    block (structural — makes the turn valid at all) immediately followed by a
    ``<turn_context>`` block, and a SEPARATE skill-invocation entry carrying the entire
    onboarding-new-user skill body (content — the ``_onw_skill`` marker other transcript
    readers already know to skip, see ``ai/assistant.py``'s own reconstruction). Neither
    is the client's own words. Without this fix that content got quoted back to the
    suggestions model as "The client asked: [500 words of internal instructions]" — noisy
    enough to bury the very next rule (never guess the client's name) in front of it.
    """
    assistant_text = ""
    user_text = ""
    # Walk backwards: find the last assistant text, then the user message before it.
    for i in range(len(history) - 1, -1, -1):
        msg = history[i]
        if msg.get("role") == "assistant" and not assistant_text:
            txt = _block_text(msg.get("content"))
            if txt.strip():
                assistant_text = txt
                # find preceding user text
                for j in range(i - 1, -1, -1):
                    if history[j].get("_onw_skill"):
                        continue  # a skill invocation, never the client's own words
                    if history[j].get("role") == "user":
                        ut = _real_client_text(history[j].get("content"))
                        # skip tool_result-only / harness-authored user messages (no
                        # real client text)
                        if ut:
                            user_text = ut
                            break
                break
    if not assistant_text:
        return None
    return user_text, assistant_text


def _valued_summary(base_ccy: str) -> list[str]:
    """
    Compact valued snapshot (magnitudes only) so starters can be concentration-aware
    — e.g. flag a dominant holding, a large cash pile, or heavy liabilities.
    Mirrors briefing.py valuation (qty×price→base, account balances→base).
    Best-effort: returns [] on any failure so starters still generate qualitatively.
    """
    try:
        to_base = ledger_service.to_base

        # Aggregate by instrument — the same holding can sit in multiple accounts
        # as separate positions; concentration is about the instrument, not the lot.
        by_name: dict[str, float] = {}
        for r in read_rows():
            if not r.get("ticker") or float(r.get("price") or 0) == 1.0:
                continue
            qty = float(r.get("quantity") or 0)
            price = float(r.get("price") or 0)
            ccy = r.get("currency", base_ccy)
            val = to_base(qty * price, ccy, base_ccy)
            if val:
                name = str(r.get("label") or r.get("ticker"))
                by_name[name] = by_name.get(name, 0.0) + val
        holdings = list(by_name.items())
        invest_total = sum(by_name.values())

        cash_total = 0.0
        liab_total = 0.0  # raw-negative
        txns = ledger_service.transactions.all()
        accts = ledger_service.accounts.query_accounts()
        cutoffs = ledger_service.cutoffs_by_account(accts, txns)
        for a in accts:
            bal_b = to_base(
                ledger_service.account_balance(a, txns, cutoffs[a["id"]]),
                a.get("currency", base_ccy),
                base_ccy,
            )
            if a.get("kind") == "asset":
                cash_total += bal_b
            else:
                liab_total += bal_b
        nw = invest_total + cash_total + liab_total

        lines: list[str] = []
        if nw:
            lines.append(f"Net worth: ~{base_ccy} {round(nw):,}")
        if holdings and invest_total:
            holdings.sort(key=lambda x: x[1], reverse=True)
            weights = ", ".join(
                f"{name} {round(v / invest_total * 100)}%" for name, v in holdings[:5]
            )
            lines.append(
                f"Investments: ~{base_ccy} {round(invest_total):,} — top by weight: {weights}"
            )
        if cash_total:
            lines.append(f"Liquid cash: ~{base_ccy} {round(cash_total):,}")
        if liab_total:
            lines.append(f"Liabilities: ~{base_ccy} {round(abs(liab_total)):,}")
        return lines
    except Exception:
        logger.exception("valued summary failed (non-fatal)")
        return []


def _starter_context() -> str:
    profile = read_profile()
    base_ccy = (profile.get("base_currency") or "USD").upper()

    holdings: list[str] = []
    seen: set[str] = set()
    try:
        for r in read_rows():
            if r.get("ticker") and float(r.get("price") or 0) != 1.0:
                label = f"{r.get('label')} ({r.get('ticker')})"
                if label not in seen:
                    seen.add(label)
                    holdings.append(label)
    except Exception:
        pass

    accounts = []
    try:
        for a in ledger_service.accounts.query_accounts():
            kind = "asset" if a.get("kind") == "asset" else "liability"
            accounts.append(f"{a.get('name')} [{kind}, {str(a.get('type', '')).replace('_', ' ')}]")
    except Exception:
        pass

    if not accounts and not holdings:
        stage = "NEW USER — no accounts and no investment positions yet"
    elif not holdings:
        stage = "ACCOUNTS ONLY — bank/credit accounts but no investments yet"
    else:
        stage = "INVESTOR — has investment positions"

    bits = [
        f"Base currency: {base_ccy}",
        f"User stage: {stage}",
        "Investment holdings: " + (", ".join(holdings[:12]) or "(none)"),
        "Accounts: " + (", ".join(accounts[:12]) or "(none)"),
    ]
    snapshot = _valued_summary(base_ccy)
    if snapshot:
        bits.append("Approximate values (snapshot — may be minutes stale):")
        bits.extend(f"  {line}" for line in snapshot)
    if profile.get("retirement_target_age"):
        bits.append(f"Retirement target age: {profile['retirement_target_age']}")
    # P2-GO1: savings goals are the Targets engine now (the free-text profile.goals[] was retired).
    try:
        from backend.services import targets as targets_service

        goal_rows = targets_service.list_hydrated(status="active")
        if goal_rows:
            names = ", ".join(str(r.get("name") or "Goal") for r in goal_rows[:5])
            bits.append(f"Goals: {names}")
    except Exception:
        pass
    return "\n".join(bits)


async def _generate(system: str, tool: dict, prompt: str) -> List[str]:
    """Provider-agnostic suggestion generation via the structured-output layer: derive a
    schema from ``_Suggestions``, validate/reask, and return the normalized strings — so it
    runs on whatever provider the 'suggestions' task (or the instance default) resolves to.
    Best-effort: a ``None`` result (unusable output even after a reask) returns [] and the UI
    falls back to its static hints. Cost is recorded by the seam via the ``source`` tag."""
    # The tool's own schema description carries the count/voice guidance (4 starters vs
    # 3 follow-ups); reuse it so the JSON prompt keeps that nuance.
    hint = (
        tool.get("input_schema", {}).get("properties", {}).get("suggestions", {}).get("description")
        or "a few short suggestion strings"
    )
    json_system = (
        f"{system}\n\nReturn ONLY a JSON object of the form "
        f'{{"suggestions": ["...", "..."]}} — {hint} '
        "No prose, no explanation, no code fence."
    )
    try:
        result = await complete_model(
            prompt,
            _Suggestions,
            system=json_system,
            model=_suggestions_model(),
            max_tokens=400,
            source="chat_suggestions",
            effort="none",  # short tappable replies — reasoning adds latency + cost, no value
        )
    except Exception:
        # Suggestion chips are decorative — the UI has static hints to fall back on. A
        # provider hiccup here (seen live: the Claude CLI returning `error_max_turns`)
        # used to surface as a 500 on /api/chat/suggestions and a red error in the log
        # for a feature nobody asked for. Degrade to no chips instead.
        logger.warning("chat suggestions unavailable", exc_info=True)
        return []
    if result is None:
        return []
    return [s.strip() for s in result.suggestions if s.strip()][:4]


@router.post("/api/chat/suggestions")
async def chat_suggestions(req: SuggestionsRequest, request: Request):
    # Master switch (Settings → Appearance → Chat). When off, never build context
    # or call the model — the chat panel falls back to its static starter hints.
    if not read_profile().get("chat_suggestions_enabled", True):
        return {"suggestions": []}

    # FOLLOW-UP mode: session exists and has a completed assistant turn. On a public demo
    # only for the visitor's own conversation — another visitor's falls back to starters.
    if req.session_id and demo_visitors.may_access(
        req.session_id, visitor_of(request), write=False
    ):
        history = assistant._load_session(req.session_id) or assistant.SESSIONS.get(req.session_id)
        if history:
            exchange = _last_exchange(history)
            if exchange:
                user_q, assistant_a = exchange
                if menu := onboarding_menu_choices(history, assistant_a):
                    return {"suggestions": menu}
                prompt = (
                    f"The client asked:\n{user_q[:1500] or '(opening message)'}\n\n"
                    f"You replied:\n{assistant_a[:3000]}\n\n"
                    f"{home_currency_line()}\n"
                    "Decide case A or B, then propose what the client would tap to send next."
                )
                return {"suggestions": await _generate(_FOLLOWUP_SYSTEM, _FOLLOWUP_TOOL, prompt)}

    # STARTER mode (cached briefly — portfolio context changes slowly).
    now = time.time()
    cached = _STARTER_CACHE.get("value")
    if cached and (now - float(_STARTER_CACHE.get("at") or 0)) < _STARTER_TTL_SEC:
        return {"suggestions": cached}

    prompt = f"Client context:\n{_starter_context()}\n\nPropose 4 opening questions."
    suggestions = await _generate(_STARTER_SYSTEM, _STARTER_TOOL, prompt)
    if suggestions:
        _STARTER_CACHE["value"] = suggestions
        _STARTER_CACHE["at"] = now
    return {"suggestions": suggestions}
