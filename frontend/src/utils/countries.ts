/** Normalize a stored or typed country value to the canonical name in COUNTRIES.
 *
 *  Resolution order:
 *    1. Already exactly a canonical name → return as-is
 *    2. Matches a 2-letter ISO code → return canonical name
 *    3. Matches a known alias → return canonical name
 *    4. Unknown → return the original value unchanged (custom / legacy entry)
 */
export function resolveCountryInput(value: string): string {
  if (!value) return value
  const trimmed = value.trim()

  // 1. Exact canonical name match (case-insensitive)
  const byName = lookupByName(trimmed)
  if (byName) return byName.name

  // 2. ISO code match (2 chars)
  if (trimmed.length === 2) {
    const byCode = lookupByCode(trimmed)
    if (byCode) return byCode.name
  }

  // 3. Alias table
  const alias = ALIASES[trimmed.toLowerCase()]
  if (alias) return alias

  // 4. Unknown — preserve the original so user data is never silently wiped
  return trimmed
}
