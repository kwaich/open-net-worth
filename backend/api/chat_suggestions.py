"""
POST /api/chat/suggestions  body: { session_id?: str }

Dynamic message suggestions for the chat panel, generated by a small/fast model:

- STARTER mode (no session / empty history): 4 opening questions tailored to the
  user's actual portfolio, accounts and stage.
- FOLLOW-UP mode (session has a completed assistant turn): 3 short questions the
  user would naturally ask next, based on the last exchange.

Best-effort: any failure returns { suggestions: [] } so the UI falls back to its
static hints. Mirrors backend/api/briefing.py (forced tool-output, Haiku).
"""

